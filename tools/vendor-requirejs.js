/* eslint-disable */
const fs = require('fs')
const Path = require('path')
const { minify } = require('terser')
/* eslint-enable */

// Writes src/requirejs.ts from the pinned requirejs devDependency, so the SDK ships RequireJS
// instead of fetching it from requirejs.org at runtime. Run after changing the requirejs version.
const source = fs.readFileSync(require.resolve('requirejs/require.js'), 'utf8')
const { version } = require('requirejs/package.json')

minify(source, { format: { comments: /@license/ } }).then(({ code }) => {
  const output = `// Generated by tools/vendor-requirejs.js from requirejs@${version} (MIT). Don't edit by hand.
export const REQUIREJS_VERSION = "${version}";
export const REQUIREJS_SOURCE: string = ${JSON.stringify(code)};
`
  fs.writeFileSync(Path.join(__dirname, '../src/requirejs.ts'), output)
})
